"""Export FastAPI OpenAPI 3.1 specification (`docs/api/openapi.json`) and TypeScript types (`apps/web/src/api/generated.ts`)."""

from __future__ import annotations

import json
import tempfile
from pathlib import Path
from typing import Any

from ai_sdlc_saas.api.app import create_app
from ai_sdlc_saas.config import Settings

ROOT = Path(__file__).resolve().parent.parent


def _ts_type(schema: dict[str, Any], schemas: dict[str, Any]) -> str:
    if "$ref" in schema:
        ref = schema["$ref"].rsplit("/", 1)[-1]
        return _sanitize_ident(ref)
    if "enum" in schema:
        vals = [json.dumps(v) for v in schema["enum"]]
        return " | ".join(vals) if vals else "string"
    if "anyOf" in schema:
        parts = [_ts_type(sub, schemas) for sub in schema["anyOf"]]
        dedup = list(dict.fromkeys(parts))
        return " | ".join(dedup)
    if "oneOf" in schema:
        parts = [_ts_type(sub, schemas) for sub in schema["oneOf"]]
        return " | ".join(list(dict.fromkeys(parts)))
    t = schema.get("type")
    if isinstance(t, list):
        return " | ".join(_ts_type({**schema, "type": item}, schemas) for item in t)
    if t == "string":
        return "string"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        items = schema.get("items") or {}
        return f"Array<{_ts_type(items, schemas)}>"
    if t == "object":
        addl = schema.get("additionalProperties")
        if isinstance(addl, dict):
            return f"Record<string, {_ts_type(addl, schemas)}>"
        props = schema.get("properties") or {}
        if not props:
            return "Record<string, unknown>"
        req = set(schema.get("required") or [])
        fields = [
            f"{json.dumps(k)}{'' if k in req else '?'}: {_ts_type(v, schemas)}"
            for k, v in props.items()
        ]
        return "{ " + "; ".join(fields) + " }"
    return "unknown"


def _sanitize_ident(name: str) -> str:
    return "".join(ch if ch.isalnum() or ch == "_" else "_" for ch in name)


def generate_typescript_from_openapi(spec: dict[str, Any]) -> str:
    schemas: dict[str, Any] = (spec.get("components") or {}).get("schemas") or {}
    lines: list[str] = [
        "/* AUTO-GENERATED by scripts/export_openapi.py from FastAPI OpenAPI schema. Do not edit manually. */",
        "",
    ]

    for name in sorted(schemas):
        schema = schemas[name]
        ts_name = _sanitize_ident(name)
        if schema.get("type") == "object" or "properties" in schema:
            props: dict[str, Any] = schema.get("properties") or {}
            req = set(schema.get("required") or [])
            lines.append(f"export interface {ts_name} {{")
            for prop_name, prop_schema in props.items():
                opt = "" if prop_name in req else "?"
                prop_key = prop_name if prop_name.isidentifier() else json.dumps(prop_name)
                lines.append(f"  {prop_key}{opt}: {_ts_type(prop_schema, schemas)};")
            lines.append("}")
            lines.append("")
        else:
            lines.append(f"export type {ts_name} = {_ts_type(schema, schemas)};")
            lines.append("")

    paths = sorted((spec.get("paths") or {}).keys())
    lines.append("export const OPENAPI_PATHS = [")
    for p in paths:
        lines.append(f"  {json.dumps(p)},")
    lines.append("] as const;")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as tmp:
        tmp_path = Path(tmp)
        settings = Settings(
            env="test",
            database_url=f"sqlite:///{tmp_path / 'openapi.db'}",
            object_store_dir=str(tmp_path / "objects"),
            worktree_root=str(tmp_path / "worktrees"),
            jwt_secret="openapi-export-secret-key-min-32-chars",
            encryption_key="MDEyMzQ1Njc4OWFiY2RlZjAxMjM0NTY3ODlhYmNkZWY=",
        )
        app = create_app(settings)
        spec = app.openapi()
        app.state.runtime.engine.dispose()

    openapi_out = ROOT / "docs" / "api" / "openapi.json"
    openapi_out.parent.mkdir(parents=True, exist_ok=True)
    openapi_out.write_text(json.dumps(spec, indent=2, sort_keys=True) + "\n", encoding="utf-8")

    ts_out = ROOT / "apps" / "web" / "src" / "api" / "generated.ts"
    ts_out.parent.mkdir(parents=True, exist_ok=True)
    ts_out.write_text(generate_typescript_from_openapi(spec), encoding="utf-8")
    print(f"Exported {len(spec.get('paths', {}))} OpenAPI paths to {openapi_out} and {ts_out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
